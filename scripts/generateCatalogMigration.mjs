#!/usr/bin/env node
/**
 * Generates supabase/migrations/20261019000000_catalogue.sql from the
 * single source of truth, scripts/lib/catalogV2.mjs, so the static
 * catalogue (themes, metrics, screen panels, food categories,
 * conditions) exists before any later migration that references it
 * (e.g. 20261022_goals_education_portions.sql inserts
 * body_system_education rows keyed on theme_id).
 *
 * Run this whenever catalogV2.mjs changes — don't hand edit the
 * generated migration.
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { THEMES, METRICS, SCREEN_PANELS, FOOD_CATEGORIES, CONDITIONS } from "./lib/catalogV2.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT = join(__dirname, "../supabase/migrations/20261019000000_catalogue.sql");

function sqlLiteral(v) {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number") return String(v);
  return `'${String(v).replace(/'/g, "''")}'`;
}

function insertStatement(table, rows, conflictCol = "id") {
  if (!rows.length) return "";
  // Union of keys across every row (not just rows[0]) — some rows in
  // these arrays carry extra columns (e.g. only the "diversity" metric
  // has scale_min/scale_max). A row missing a column gets an explicit
  // null, same as the Supabase JS client's own bulk-insert semantics.
  const cols = [...new Set(rows.flatMap(row => Object.keys(row)))];
  const values = rows
    .map(row => `  (${cols.map(c => sqlLiteral(row[c])).join(", ")})`)
    .join(",\n");
  const updates = cols.filter(c => c !== conflictCol).map(c => `${c} = excluded.${c}`).join(", ");
  return `insert into ${table} (${cols.join(", ")}) values\n${values}\non conflict (${conflictCol}) do update set ${updates};\n`;
}

const sql = `-- Generated by scripts/generateCatalogMigration.mjs from scripts/lib/catalogV2.mjs.
-- Do not hand edit — rerun the generator instead.
--
-- The static catalogue (same rows in every environment, no client
-- data): themes, metrics, screen panels, food categories, conditions.
-- Must run before any later migration that references these rows
-- (body_system_education, marker_labels, swap_pairs, ...).
begin;

${insertStatement("themes", THEMES)}
${insertStatement("metrics", METRICS)}
${insertStatement("screen_panels", SCREEN_PANELS)}
${insertStatement("food_categories", FOOD_CATEGORIES)}
${insertStatement("conditions", CONDITIONS)}
commit;
`;

writeFileSync(OUT, sql);
console.log(`Wrote ${OUT}`);
